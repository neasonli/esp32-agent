export type I18nKey = keyof typeof zh

/** 语言感知的翻译 hook：组件订阅 lang 变化自动重渲染 */
export function useT(): (key: I18nKey) => string {
  const lang = useAppStore((s) => s.lang)
  return (key) => (lang === 'zh' ? zh[key] : en[key])
}

export function statusText(status: string, lang: 'zh' | 'en'): string {
  const map: Record<string, [string, string]> = {
    PENDING: ['排队中', 'Queued'],
    RUNNING: ['执行中', 'Running'],
    SUCCESS: ['成功', 'Success'],
    FAILED: ['失败', 'Failed'],
    CANCELED: ['已取消', 'Canceled'],
    INTERRUPTED: ['已中断', 'Interrupted']
  }
  const pair = map[status]
  if (!pair) return status
  return lang === 'zh' ? pair[0] : pair[1]
}
